--- Подпись значения куки.
---
--- Кука лежит у пользователя, и он волен её переписать: значение `admin=0`
--- меняется на `admin=1` в любом браузере за пять секунд. Подпись не прячет
--- значение — оно по-прежнему читается глазами, — но делает его
--- неизменяемым: без ключа подпись к подменённому значению не собрать.
---
--- Считается HMAC-SHA256. Простой хеш `sha256(key .. value)` здесь не
--- годится: его наращивают с хвоста, не зная ключа (length extension),
--- и подпись к дописанному значению собирается из чужой подписи.
---
--- Сравнение подписей идёт до конца, а не до первого несовпадения. Выход
--- на первом несовпавшем байте отвечает не «сошлось ли», а «сколько байтов
--- сошлось», и по времени ответа подпись подбирается побайтно — за сотни
--- попыток вместо астрономического числа.
---
--- И подпись, и сравнение берутся у `tnt-hash`. Вид подписи при переезде
--- на него остался прежним — HMAC-SHA256 в base64url, — и уже выданные
--- куки открываются как открывались.

local hash = require('tnt.hash')

local Module = {}

--- Чем подпись отделена от значения.
---
--- Точка: она разрешена в значении куки и не встречается в base64url,
--- поэтому последняя точка строки — всегда граница, какое бы ни было
--- само значение.
local SEPARATOR = '.'

--- Ключ обязателен: подпись пустым ключом — не подпись, а её вид.
---
--- Исключением, а не отказом: ключ берётся из настроек, и его отсутствие —
--- не чужая ошибка, которую надо пережить, а своя, которую надо заметить
--- при первом же запуске.
---@param key any
---@param level integer Уровень вины, как у `error` в вызывающем
local function demand_key(key, level)
    if type(key) ~= 'string' or key == '' then
        error('подписать куку нечем: задайте ключ настройкой key', level + 1)
    end
end

--- Уровень вины для `error` в самой подписи.
---
--- Место в отказе — строка того, кто подпись позвал: чинить надо его
--- настройку или его вызов, а строка внутри пакета отправила бы искать
--- ошибку не туда. Фасад пакета зовёт подпись через свои кадры и потому
--- передаёт уровень явно; по умолчанию виноват прямой вызывающий.
---@param level integer|nil Как у `error` в вызывающем подписи
---@return integer
local function blamed(level)
    return (level or 1) + 1
end

--- Подпись значения в base64url.
---
--- Алфавит, безопасный для адресов: знаки `+`, `/` и `=` обычного base64
--- либо запрещены в куке, либо мешают разобрать её обратно, а набивки
--- у этого вида нет.
---@param value string
---@param key string
---@return string
local function digest_of(value, key)
    return hash.hmac('sha256', key, value, 'base64url')
end

--- Подписывает значение.
---@param value string Что подписать
---@param key string Ключ подписи
---@param level integer|nil Уровень вины, как у `error` в вызывающем; по умолчанию — он сам
---@return string signed Значение с подписью через точку
function Module.make(value, key, level)
    local blame = blamed(level)

    demand_key(key, blame)

    if type(value) ~= 'string' then
        error(('подписать можно строку, а не %s'):format(type(value)), blame)
    end

    return value .. SEPARATOR .. digest_of(value, key)
end

--- Снимает подпись, проверив её.
---@param text any Значение с подписью
---@param key string Ключ подписи
---@param level integer|nil Уровень вины, как у `error` в вызывающем; по умолчанию — он сам
---@return string|nil value Значение без подписи
---@return string|nil err
function Module.open(text, key, level)
    demand_key(key, blamed(level))

    if type(text) ~= 'string' then
        return nil,
            ('подписанное значение должно быть строкой, а не %s'):format(
                type(text)
            )
    end

    -- Граница — последняя точка: значение вправе содержать свои,
    -- а base64url — нет.
    local value, signature = text:match('^(.*)%.([^.]*)$')

    if value == nil then
        return nil, 'в значении нет подписи: она отделяется точкой в конце'
    end

    if not hash.equals(digest_of(value, key), signature) then
        return nil,
            'подпись значения не сошлась: значение переписано или ключ не тот'
    end

    return value
end

return Module
